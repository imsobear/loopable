/**
 * Manifests name their icon as a string so no connector ships a component into
 * the client bundle. Names resolve here, explicitly, to keep the bundle from
 * pulling in a whole icon set.
 */
const MARKS: Record<string, Mark> = {
  Github: GithubMark,
  Slack: SlackMark,
  Feishu: FeishuMark,
  Gmail: GmailMark,
  Wechat: WechatMark,
  Codex: CodexMark,
  ClaudeCode: ClaudeCodeMark,
  Cursor: CursorMark,
};

/** Not products: a clock is the thing itself, and a plug is the fallback. */
const GLYPHS: Record<string, LucideIcon> = { Clock, Plug };

/** A product's logo on a tile. `accent` is no longer drawn; manifests still carry it. */
export function ConnectorIcon({
  icon,
  className,
}: {
  icon: string;
  accent?: string;
  className?: string;
}) {
  const Mark = MARKS[icon];
  if (Mark) {
    return (
      <span
        className={cn(
          "flex size-9 shrink-0 items-center justify-center rounded-lg bg-white ring-1 ring-foreground/10 dark:bg-neutral-900",
          className,
        )}
      >
        <Mark className="size-[55%]" />
      </span>
    );
  }
  const Glyph = GLYPHS[icon] ?? Plug;
  return (
    <span
      className={cn(
        "flex size-9 shrink-0 items-center justify-center rounded-lg bg-muted text-muted-foreground",
        className,
      )}
    >
      <Glyph className="size-[55%]" />
    </span>
  );
}

